def inject_noise(doc: dict) -> str:
    """Імітує сирий експорт веб/PDF-документа з навігацією, банерами й колонтитулами."""
    lines = [
        "<!-- NAV_START -->",
        "[Головна] | [Лісовий каталог] | [Моніторинг] | [Документи] | [Вхід у систему]",
        "Пошук по сайту: [________________] [Знайти]",
        "<!-- NAV_END -->",
        f"<h1>{doc['title']}</h1>",
        f"Дата публікації: {doc['date']} | Категорія: {doc['type']} | Доступ: {doc['sensitivity']}",
        "",
    ]
    for page_idx, (sec_title, paragraphs) in enumerate(doc["sections"], start=1):
        lines.append(f"## {sec_title}")
        lines.append("")
        for p in paragraphs:
            lines.append(p)
            lines.append("")
        lines.append(f"--- Сторінка {page_idx} з {len(doc['sections'])} | Domain Knowledge Hub ---")
        lines.append("")
    lines.append("© 2026 Domain Knowledge Hub · Усі права захищено · Політика конфіденційності · Cookies")
    return "\n".join(lines)


def clean_document(raw_text: str):
    """
    Правила очищення від шуму (C2):
      1. Видалення блоків навігації <!-- NAV_START --> ... <!-- NAV_END --> та рядків меню [Головна] | ...
      2. Видалення колонтитулів виду '--- Сторінка N з M ... ---' та рядків копірайту '© 2026 ...'
      3. Видалення HTML-тегів (<h1>...</h1> → # ...) і службових рядків форми пошуку.
      4. Нормалізація пробілів, нерозривних пробілів і порожніх рядків (не більше 1 підряд).
    """
    stats = {"raw_chars": len(raw_text)}
    text = re.sub(r"<!--\s*NAV_START\s*-->.*?<!--\s*NAV_END\s*-->", "", raw_text, flags=re.S)
    text = re.sub(r"^\[Головна\].*$", "", text, flags=re.M)
    text = re.sub(r"^Пошук по сайту:.*$", "", text, flags=re.M)
    text = re.sub(r"^---\s*Сторінка\s+\d+\s+з\s+\d+.*---$", "", text, flags=re.M)
    text = re.sub(r"^©\s*\d{4}.*$", "", text, flags=re.M)
    text = re.sub(r"<h1>(.*?)</h1>", r"# \1", text)
    text = re.sub(r"<[^>]+>", "", text)
    text = text.replace("\u00a0", " ")
    text = re.sub(r"[ \t]+", " ", text)
    text = re.sub(r"\n{3,}", "\n\n", text).strip()
    stats["clean_chars"] = len(text)
    stats["removed_chars"] = stats["raw_chars"] - stats["clean_chars"]
    return text, stats


def split_into_corpus_chunks(clean_text: str, doc: dict):
    """
    Базове розбиття на фрагменти (речення/абзаци в межах секцій) для data/corpus.jsonl
    так, щоб забезпечити >=200 фрагментів із точними метаданими.
    """
    chunks = []
    current_section = "Вступ"
    lines = clean_text.splitlines()
    buf = []

    def flush_paragraph(para_text):
        # Ділимо довгі абзаци по реченнях (1-2 речення на фрагмент ~25-45 слів)
        sents = re.split(r"(?<=[.!?])\s+(?=[А-ЯІЇЄҐA-Z0-9])", para_text.strip())
        for s in sents:
            s = s.strip()
            if len(s) >= 25:
                chunks.append((current_section, s))

    for ln in lines:
        ln_s = ln.strip()
        if not ln_s:
            if buf:
                flush_paragraph(" ".join(buf))
                buf = []
            continue
        if ln_s.startswith("# "):
            continue
        if ln_s.startswith("Дата публікації:"):
            continue
        if ln_s.startswith("## "):
            if buf:
                flush_paragraph(" ".join(buf))
                buf = []
            current_section = ln_s[3:].strip()
            continue
        buf.append(ln_s)
    if buf:
        flush_paragraph(" ".join(buf))

    records = []
    for idx, (sec, txt) in enumerate(chunks, start=1):
        records.append({
            "chunk_id": f"{doc['doc_id']}_C{idx:02d}",
            "doc_id": doc["doc_id"],
            "title": doc["title"],
            "section": sec,
            "type": doc["type"],
            "date": doc["date"],
            "sensitivity": doc["sensitivity"],
            "source_url": doc["source_url"],
            "text": txt,
        })
    return records


def main():
    for d in (RAW_DIR, KB_DIR, DATA_DIR, OUT_DIR):
        os.makedirs(d, exist_ok=True)

    all_chunks = []
    total_raw = 0
    total_clean = 0
    sens_cnt = Counter()
    type_cnt = Counter()

    for doc in DOCS:
        raw = inject_noise(doc)
        with open(os.path.join(RAW_DIR, f"{doc['doc_id']}.md"), "w", encoding="utf-8") as fh:
            fh.write(raw)

        clean, st = clean_document(raw)
        total_raw += st["raw_chars"]
        total_clean += st["clean_chars"]
        with open(os.path.join(KB_DIR, f"{doc['doc_id']}.md"), "w", encoding="utf-8") as fh:
            fh.write(clean + "\n")

        recs = split_into_corpus_chunks(clean, doc)
        for r in recs:
            sens_cnt[r["sensitivity"]] += 1
            type_cnt[r["type"]] += 1
        all_chunks.extend(recs)

    corpus_path = os.path.join(DATA_DIR, "corpus.jsonl")
    with open(corpus_path, "w", encoding="utf-8") as fh:
        for r in all_chunks:
            fh.write(json.dumps(r, ensure_ascii=False) + "\n")

    summary = {
        "documents": len(DOCS),
        "chunks": len(all_chunks),
        "avg_chunk_words": round(sum(len(r["text"].split()) for r in all_chunks) / len(all_chunks), 1),
        "avg_chunk_chars": round(sum(len(r["text"]) for r in all_chunks) / len(all_chunks), 1),
        "raw_chars": total_raw,
        "clean_chars": total_clean,
        "noise_removed_chars": total_raw - total_clean,
        "noise_removed_pct": round(100.0 * (total_raw - total_clean) / total_raw, 2),
        "by_sensitivity": dict(sens_cnt),
        "by_type": dict(type_cnt),
    }
    with open(os.path.join(OUT_DIR, "corpus_stats.json"), "w", encoding="utf-8") as fh:
        json.dump(summary, fh, ensure_ascii=False, indent=2)

    print(json.dumps(summary, ensure_ascii=False, indent=2))
    assert summary["documents"] >= 20, "Потрібно >=20 документів"
    assert summary["chunks"] >= 200, f"Потрібно >=200 фрагментів, отримано {summary['chunks']}"
    print("OK: корпус відповідає всім вимогам Результату 1.")


if __name__ == "__main__":
    main()
